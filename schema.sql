-- 1. TABLA DE SERVICIOS / TIPOS DE SESIÓN (services)
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    duration_minutes INT DEFAULT 60 NOT NULL,
    grace_minutes INT DEFAULT 25 NOT NULL,
    price NUMERIC(10, 2) DEFAULT NULL,
    description TEXT DEFAULT '',
    is_featured BOOLEAN DEFAULT false NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABLA DE CITAS / RESERVAS E HISTORIAL (appointments)
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code TEXT UNIQUE NOT NULL,
    client_name TEXT NOT NULL,
    service_id BIGINT REFERENCES public.services(id) ON DELETE SET NULL,
    service_name TEXT NOT NULL,
    people_count INT DEFAULT 1 NOT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME NOT NULL,
    client_email TEXT DEFAULT '',
    client_phone TEXT DEFAULT '',
    grace_minutes INT DEFAULT 25 NOT NULL,
    status TEXT DEFAULT 'pendiente' NOT NULL,
    estimated_price NUMERIC(10, 2) DEFAULT NULL,
    client_notes TEXT DEFAULT '',
    admin_notes TEXT DEFAULT '',
    arrived_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Asegurar columna de correo electrónico y teléfono flexible si la tabla ya fue creada:
ALTER TABLE public.appointments ADD COLUMN IF NOT EXISTS client_email TEXT DEFAULT '';
ALTER TABLE public.appointments ALTER COLUMN client_phone DROP NOT NULL;

-- 3. HABILITAR ROW LEVEL SECURITY (RLS) Y POLÍTICAS PÚBLICAS
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir acceso completo a services" ON public.services;
CREATE POLICY "Permitir acceso completo a services"
ON public.services FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso completo a appointments" ON public.appointments;
CREATE POLICY "Permitir acceso completo a appointments"
ON public.appointments FOR ALL USING (true) WITH CHECK (true);
